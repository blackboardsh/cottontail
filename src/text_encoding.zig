fn isAsciiWhitespace(byte: u8) bool {
    return switch (byte) {
        ' ', '\t', '\n', '\r', 0x0c => true,
        else => false,
    };
}

pub export fn ct_text_encoding_lookup(input: ?[*]const u8, input_len: usize) c_int {
    const bytes = if (input) |pointer| pointer[0..input_len] else return -1;
    var start: usize = 0;
    var end = bytes.len;
    while (start < end and isAsciiWhitespace(bytes[start])) start += 1;
    while (end > start and isAsciiWhitespace(bytes[end - 1])) end -= 1;

    const label = bytes[start..end];
    if (label.len == 0 or label.len > 64) return -1;
    var normalized: [64]u8 = undefined;
    for (label, 0..) |byte, index| {
        normalized[index] = if (byte >= 'A' and byte <= 'Z') byte + ('a' - 'A') else byte;
    }
    const encoding = labels.get(normalized[0..label.len]) orelse return -1;
    return @intFromEnum(encoding);
}

pub export fn ct_text_encoding_decode_single_byte(
    encoding_number: c_int,
    input: ?[*]const u8,
    input_len: usize,
    output: ?[*]u16,
    fatal: c_int,
) c_int {
    if (encoding_number < 0 or encoding_number > std.math.maxInt(u8)) {
        return @intFromEnum(single_byte.Result.unsupported);
    }
    if (input_len == 0) {
        const encoding: u8 = @intCast(encoding_number);
        return @intFromEnum(single_byte.decode(encoding, &.{}, &.{}, fatal != 0));
    }
    const bytes = if (input) |pointer| pointer[0..input_len] else return 0;
    const code_units = if (output) |pointer| pointer[0..input_len] else return 0;
    return @intFromEnum(single_byte.decode(
        @intCast(encoding_number),
        bytes,
        code_units,
        fatal != 0,
    ));
}

test "WHATWG encoding aliases resolve case-insensitively after ASCII trimming" {
    try std.testing.expectEqual(@as(c_int, 21), ct_text_encoding_lookup(" \tLaTiN1\r".ptr, 9));
    try std.testing.expectEqual(@as(c_int, 0), ct_text_encoding_lookup("UNICODE11UTF8".ptr, 13));
    try std.testing.expectEqual(@as(c_int, 34), ct_text_encoding_lookup("shift-jis".ptr, 9));
    try std.testing.expectEqual(@as(c_int, -1), ct_text_encoding_lookup("utf-9".ptr, 5));
}
