#!/usr/bin/env node

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const schemaPath = join(root, "src", "native_bindings", "direct-bindings.json");
const outputPath = join(root, "src", "native_bindings", "direct-bindings.generated.inc");
const bindings = JSON.parse(readFileSync(schemaPath, "utf8"));
const names = new Set();
const callbacks = new Set();

for (const binding of bindings) {
  if (!binding || typeof binding.name !== "string" || !binding.name) {
    throw new Error("Every direct binding requires a non-empty name");
  }
  if (!Number.isInteger(binding.arity) || binding.arity < 0) {
    throw new Error(`Direct binding ${binding.name} has an invalid arity`);
  }
  if (!/^[A-Za-z_][A-Za-z0-9_]*$/.test(binding.callback)) {
    throw new Error(`Direct binding ${binding.name} has an invalid C callback`);
  }
  if (names.has(binding.name)) throw new Error(`Duplicate direct binding name: ${binding.name}`);
  if (callbacks.has(binding.callback)) throw new Error(`Duplicate direct binding callback: ${binding.callback}`);
  names.add(binding.name);
  callbacks.add(binding.callback);
}

const output = [
  "/* Generated by scripts/generate-native-bindings.js. */",
  ...bindings.map(binding =>
    `CT_DIRECT_NATIVE_BINDING(${JSON.stringify(binding.name)}, ${binding.arity}, ${binding.callback})`
  ),
  "",
].join("\n");

if (process.argv.includes("--check")) {
  if (readFileSync(outputPath, "utf8") !== output) {
    throw new Error(`${outputPath} is stale; run scripts/generate-native-bindings.js`);
  }
} else {
  writeFileSync(outputPath, output);
}
